-- =============================================================================
--  ІСІХАСТ — новини оновлюємо раз на добу (замість кожних 5 годин).
-- =============================================================================
--  Канали публікують нечасто, тож щоденного оновлення достатньо.
--  06:00 UTC = 09:00 за київським часом (влітку).
-- =============================================================================

do $$
begin
  if exists (select 1 from cron.job where jobname = 'tg_news_sync') then
    perform cron.unschedule('tg_news_sync');
  end if;
  perform cron.schedule('tg_news_sync', '0 6 * * *', 'select public.tg_news_cron_tick();');
end $$;
